#!/usr/bin/env python3
"""Make crates/ui/src/world.rs: country outlines for the audience map (#225).

Input: Natural Earth 1:110m admin-0 countries GeoJSON (public domain),
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_admin_0_countries.geojson
Usage: python3 scripts/geo/world.py <geojson> > crates/ui/src/world.rs
Projection: equirectangular, 1000 wide, latitudes 84°N to 58°S (Antarctica
left out), points closer than 0.9 px dropped, coordinates rounded to 0.1.
"""
import json
import sys

W, TOP, BOTTOM = 1000.0, 84.0, -58.0
H = W * (TOP - BOTTOM) / 360.0


def xy(lon, lat):
    return (lon + 180.0) / 360.0 * W, (TOP - lat) / (TOP - BOTTOM) * H


def ring(pts):
    out, last = [], None
    for lon, lat in pts:
        x, y = xy(lon, lat)
        if last and abs(x - last[0]) < 0.9 and abs(y - last[1]) < 0.9:
            continue
        out.append((round(x, 1), round(y, 1)))
        last = (x, y)
    if len(out) < 3:
        return ""
    s = "M" + " ".join(f"{x:g} {y:g}" for x, y in out[:1])
    s += "L" + " ".join(f"{x:g} {y:g}" for x, y in out[1:]) + "Z"
    return s


feats = json.load(open(sys.argv[1], encoding="utf-8"))["features"]
rows = []
for f in feats:
    p = f["properties"]
    iso = p.get("ISO_A2_EH") or p.get("ISO_A2")
    if not iso or iso == "-99" or p.get("ADM0_A3") == "ATA":
        continue
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    d = "".join(ring(poly[0]) for poly in polys)
    if d:
        rows.append((iso, p["NAME"].replace('"', ""), d))
rows.sort()
print("//! Country outlines for the audience map (#225). Generated by")
print("//! `scripts/geo/world.py` from Natural Earth 1:110m (public domain).")
print("//! Do not edit by hand.")
print()
print(f"/// Width and height of the map's coordinate space.")
print(f"pub const SIZE: (f64, f64) = ({W:g}.0, {H:.1f});")
print()
print("/// (ISO 3166-1 alpha-2, name, SVG path).")
print("pub const COUNTRIES: &[(&str, &str, &str)] = &[")
for iso, name, d in rows:
    print(f'    ("{iso}", "{name}", "{d}"),')
print("];")
