#!/usr/bin/env bash
# Render deploy/k8s/base/openlens.yaml from the Helm chart, so the plain
# manifests never drift from it. No Secret is rendered: the admin token comes
# from a Secret you create (see docs/deploy/kubernetes.md), or OpenLens
# generates one on first start. CI fails when the committed file is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
out=deploy/k8s/base/openlens.yaml
{
  echo "# Generated by scripts/render-k8s.sh from deploy/helm/openlens. Do not edit."
  helm template openlens deploy/helm/openlens --skip-tests \
    --set adminToken.existingSecret=openlens-admin --set adminToken.optional=true \
    | grep -v -e '^ *helm.sh/chart:' -e '^ *app.kubernetes.io/managed-by:' -e '^# Source:'
} > "$out"
echo "rendered $out"
