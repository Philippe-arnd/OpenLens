/**
 * Where a Web Vital comes from (#467): raw facts only, the advice is in the
 * engine. DOM-free so `node --test` covers it. Our own implementation of
 * the sub-parts the W3C Event Timing, LCP and Layout Instability specs and
 * the web.dev guides describe (docs/clean-room.md).
 */

/** The part of an element a selector reads (a DOM `Element` fits). */
export interface El {
  tagName: string;
  id: string;
  parentElement: El | null;
  getAttribute(name: string): string | null;
  hasAttribute(name: string): boolean;
}

/** Selectors are cut to this length, keeping the element's end. */
export const MAX_SELECTOR = 120;

/** A class or id written by a person, not generated by a build tool: no
 * digit, no CSS-in-JS prefix, no hash-like mixed-case suffix. */
export function stable(name: string): boolean {
  if (!/^[a-zA-Z][\w-]{0,39}$/.test(name) || /\d/.test(name)) return false;
  if (/^(css|sc|jsx|svelte|emotion|chakra|mui|tw)-/i.test(name)) return false;
  const tail = name.split(/[-_]+/).pop() || "";
  return tail === name || !(/[a-z]/.test(tail) && /[A-Z]/.test(tail));
}

/** One step of a selector: `tag#id`, else `tag.a.b` (two stable classes). */
function step(el: El, masked: boolean): string {
  const tag = el.tagName.toLowerCase();
  if (masked) return tag;
  if (el.id && stable(el.id)) return `${tag}#${el.id}`;
  const cls = (el.getAttribute("class") || "").split(/\s+/).filter(stable).slice(0, 2);
  return tag + cls.map((c) => "." + c).join("");
}

/** 2 under `data-openlens-ignore`, 1 under `data-openlens-mask`, else 0. */
export function hidden(el: El | null | undefined): number {
  let h = 0;
  for (let n = el; n; n = n.parentElement) {
    if (n.hasAttribute("data-openlens-ignore")) return 2;
    if (n.hasAttribute("data-openlens-mask")) h = 1;
  }
  return h;
}

/**
 * A short CSS selector for `el`: up to 3 steps, stopping at an id, cut to
 * [`MAX_SELECTOR`] characters. No text, no attribute value. Under
 * `data-openlens-ignore` nothing is sent (empty string); under
 * `data-openlens-mask` only tag names.
 */
export function selector(el: El | null | undefined): string {
  const h = hidden(el);
  if (!el || h > 1) return "";
  const up: El[] = [];
  for (let n: El | null = el; n; n = n.parentElement) up.push(n);
  const masked = h > 0;
  const parts: string[] = [];
  for (const n of up.slice(0, 3)) {
    const s = step(n, masked);
    if (parts.length && [s, ...parts].join(" > ").length > MAX_SELECTOR) break;
    parts.unshift(s);
    if (s.includes("#")) break;
  }
  return parts.join(" > ").slice(-MAX_SELECTOR);
}

/** A resource URL as path only: no query, no hash; the host only when it is
 * not the page's. Non-http URLs (`data:`, `blob:`) keep only their scheme. */
export function resourcePath(url: string, page: string): string {
  try {
    const u = new URL(url, page);
    if (!/^https?:$/.test(u.protocol)) return u.protocol;
    const p = u.host === new URL(page).host ? u.pathname : u.host + u.pathname;
    return p.slice(0, 200);
  } catch {
    return "";
  }
}

/**
 * LCP in four parts (web.dev): first byte, resource load delay, resource
 * load time, element render delay, in ms, summing to `lcp`. A text element
 * (no resource) has no load parts.
 */
export function lcpParts(lcp: number, ttfb: number, loadStart?: number, loadEnd?: number): number[] {
  const t = Math.min(Math.max(ttfb, 0), lcp);
  const start = loadStart ? Math.min(Math.max(loadStart, t), lcp) : t;
  const end = loadEnd ? Math.min(Math.max(loadEnd, start), lcp) : start;
  return [t, start - t, end - start, lcp - end].map(Math.round);
}

/** An interaction in three parts (Event Timing): input delay, processing,
 * presentation delay, in ms, summing to `duration`. */
export function inpParts(start: number, procStart: number, procEnd: number, duration: number): number[] {
  const end = start + duration;
  const a = Math.min(Math.max(procStart, start), end);
  const b = Math.min(Math.max(procEnd, a), end);
  return [a - start, b - a, end - b].map(Math.round);
}

/** phone, tablet or desktop: a touch screen as primary pointer, split on its
 * short side (the same words the server uses for page views). */
export function deviceClass(coarse: boolean, shortSide: number): string {
  return !coarse ? "desktop" : shortSide < 600 ? "phone" : "tablet";
}
